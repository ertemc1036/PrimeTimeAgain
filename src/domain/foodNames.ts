const IDX: Record<Exclude<FoodLang, 'en'>, number> = { de: 0, tr: 1, es: 2, fr: 3 };

export const foodName = (food: FoodRef, lang: FoodLang): string => (lang === 'en' ? food.name : (FOOD_NAMES[food.id]?.[IDX[lang]] ?? food.name));

/** Display label for a serving unit. The stored unit stays the English key so nutrition maths is unchanged. */
export const servingLabel = (unit: string, lang: FoodLang): string => (lang === 'en' ? unit : (SERVING_NAMES[unit]?.[IDX[lang]] ?? unit));

export const hasAllFoodNames = (ids: string[]) => ids.every((id) => FOOD_NAMES[id]?.length === 4);
export const hasAllServingNames = (labels: string[]) => labels.every((l) => SERVING_NAMES[l]?.length === 4);
